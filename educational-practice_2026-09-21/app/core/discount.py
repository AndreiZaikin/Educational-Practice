"""Расчёт индивидуальной скидки партнёра.

Модуль содержит изолированную функцию, которая по суммарному объёму
купленной партнёром продукции возвращает процент скидки согласно ТЗ.
"""


def calculate_partner_discount(total_quantity: int) -> int:
    """Вернуть процент скидки партнёра по суммарному объёму покупок.

    :param total_quantity: суммарный объём купленной продукции, ед.
    :return: процент скидки (0, 5, 10 или 15).
    """
    if total_quantity < 10_000:
        return 0

    if total_quantity < 50_000:
        return 5

    if total_quantity < 300_000:
        return 10

    return 15
